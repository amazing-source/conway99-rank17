"""Experiment: do NON-FLAT graphs with (lambda, c2) = (1, 2) exist at all?
(1,2)-graph: connected, every edge in exactly one triangle, every two vertices at distance 2 have exactly 2 common
neighbours.  Hamming graphs H(n,3) and their quotients are the flat examples.  Here: Cayley graphs Cay(G, D), D a union
of m subgroups of order 3 (minus 1), G generated by random order-3 permutations.  Test at the identity (vertex
transitive, so this is the whole graph):
   lambda = 1 : for a in D, the only b in D with ab in D is b = a;
   c2 = 2     : every g = ab at distance 2 has exactly two factorisations in D x D.
Report non-abelian hits."""
import random, itertools, sys, collections
def mul(p, q): return tuple(p[i] for i in q)          # (p*q)(i) = p[q[i]]
def inv(p):
    r = [0] * len(p)
    for i, x in enumerate(p): r[x] = i
    return tuple(r)
def rand3(n, rng):
    k = rng.randint(1, n // 3)
    pts = rng.sample(range(n), 3 * k); p = list(range(n))
    for j in range(k):
        a, b, c = pts[3*j:3*j+3]; p[a], p[b], p[c] = b, c, a
    return tuple(p)
def test(gens, cap):
    n = len(gens[0]); e = tuple(range(n))
    D = []
    for g in gens:
        for h in (g, inv(g)):
            if h not in D: D.append(h)
    if len(D) != 2 * len(gens): return None
    Dset = set(D)
    # lambda = 1 at identity
    for a in D:
        if sum(1 for b in D if mul(a, b) in Dset) != 1: return None
    # c2 at identity
    cnt = collections.Counter()
    for a in D:
        for b in D:
            g = mul(a, b)
            if g != e and g not in Dset: cnt[g] += 1
    if any(v != 2 for v in cnt.values()): return None
    # group order (BFS), capped
    seen = {e}; fr = [e]
    while fr:
        nf = []
        for x in fr:
            for d in D:
                y = mul(x, d)
                if y not in seen:
                    seen.add(y); nf.append(y)
                    if len(seen) > cap: return ('big', len(D))
        fr = nf
    abel = all(mul(a, b) == mul(b, a) for a in D for b in D)
    return (len(seen), abel)
rng = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
hits = collections.Counter(); examples = {}
trials = int(sys.argv[2]) if len(sys.argv) > 2 else 200000
for t in range(trials):
    n = rng.choice([6, 7, 8, 9, 10, 12]); m = rng.choice([2, 3, 3, 4, 4, 5])
    gens = [rand3(n, rng) for _ in range(m)]
    r = test(gens, 20000)
    if r is None: continue
    key = (m, r[0], r[1])
    hits[key] += 1
    if key not in examples: examples[key] = (n, gens)
for k in sorted(hits, key=str): print('valency', 2 * k[0], 'order', k[1], 'abelian', k[2], 'count', hits[k])
import pickle; pickle.dump(examples, open('cayley12_examples.pkl', 'wb'))
