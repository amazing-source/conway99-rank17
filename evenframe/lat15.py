"""The five unimodular lattices of rank 15, as integer Gram matrices with an explicit basis, plus short-vector shells.
Coordinates: basis rows in an ambient space scaled by 4 (so all entries are integers)."""
import numpy as np, itertools, sys
from fractions import Fraction as F

def hnf_basis(gens):
    """integer row-lattice basis (LLL-free): Hermite normal form via exact elimination"""
    M = [list(map(int, g)) for g in gens]
    n = len(M[0]); basis = []; r = 0
    M = [row[:] for row in M]
    for c in range(n):
        rows = [row for row in M if any(row[:c + 1]) and not any(row[:c]) ]
        # gather rows with first nonzero at column c
        piv = [row for row in M if row[c] != 0 and not any(row[:c])]
        rest = [row for row in M if not (row[c] != 0 and not any(row[:c]))]
        while len(piv) > 1:
            piv.sort(key=lambda x: abs(x[c]))
            a = piv[0]
            new = [a]
            for b in piv[1:]:
                q = b[c] // a[c]
                b2 = [x - q * y for x, y in zip(b, a)]
                if b2[c] != 0: new.append(b2)
                elif any(b2): rest.append(b2)
            piv = new
        if piv:
            basis.append(piv[0])
        M = rest
    return np.array(basis, dtype=np.int64)

def E8_gens():        # in 4x coordinates of R^8
    g = []
    for i in range(7): v = [0]*8; v[i] = 4; v[i+1] = -4; g.append(v)
    v = [0]*8; v[0] = 4; v[1] = 4; g.append(v)
    g.append([2]*8)
    return g
def Dn_plus_gens(n):
    g = []
    for i in range(n-1): v = [0]*n; v[i] = 4; v[i+1] = -4; g.append(v)
    v = [0]*n; v[0] = 4; v[1] = 4; g.append(v)
    g.append([2]*n)
    return g
def E7_gens():        # E7 = vectors of E8 orthogonal to (1,1,...,1)/2 ... use x in E8 with sum of coords = 0
    return None
def build(name):
    if name == 'Z15':
        B = 4 * np.eye(15, dtype=np.int64)
    elif name == 'E8Z7':
        g = [v + [0]*7 for v in E8_gens()] + [[0]*8 + [4 if j == i else 0 for j in range(7)] for i in range(7)]
        B = hnf_basis(g)
    elif name == 'D12Z3':
        g = [v + [0]*3 for v in Dn_plus_gens(12)] + [[0]*12 + [4 if j == i else 0 for j in range(3)] for i in range(3)]
        B = hnf_basis(g)
    elif name == 'E7E7Z':
        # E7 = {x in E8 : x . (1^8)/2*... } take E7 = E8 vectors orthogonal to r = (1,-1,0,...,0)
        # E7* / E7 = Z/2 generated by the projection of an E8 vector with (x, r) = 1
        import itertools as it
        E8 = hnf_basis(E8_gens())
        r = np.array([4, -4, 0, 0, 0, 0, 0, 0])
        # E7 basis: integer combinations of E8 basis orthogonal to r
        ip = (E8 @ r) // 16
        # solve: find lattice of coefficient vectors c with c . ip = 0
        from math import gcd
        coef = []
        idx = [i for i in range(8) if ip[i] != 0]
        j0 = min(idx, key=lambda i: abs(ip[i]))
        assert abs(ip[j0]) == 1
        for i in range(8):
            if i == j0: continue
            c = np.zeros(8, dtype=np.int64); c[i] = 1; c[j0] = -ip[i] * ip[j0]
            coef.append(c)
        E7 = np.array(coef) @ E8
        assert (E7 @ r == 0).all()
        x = E8[j0]                       # (x, r) = +-1
        # glue vector: projection of x onto r^perp = x - (x.r / r.r) r ; in 4x coords r.r = 32, x.r = +-16 -> x -+ r/2
        gl = 2 * x - (int(x @ r) // 16) * r          # equals 2 * projection (so entries stay integral in 8x coords)
        # work in 8x coordinates: scale everything by 2
        E7s = 2 * E7; gls = gl
        gens = []
        for v in E7s: gens.append(list(v) + [0]*8 + [0]); gens.append([0]*8 + list(v) + [0])
        gens.append(list(gls) + list(gls) + [0])
        gens.append([0]*16 + [8])
        B = hnf_basis(gens)
        return B, 8
    elif name == 'A15p':
        g = []
        for i in range(15): v = [0]*16; v[i] = 4; v[i+1] = -4; g.append(v)
        g.append([3]*4 + [-1]*12)       # glue [4] = (3/4)^4 (-1/4)^12
        B = hnf_basis(g)
    else:
        raise ValueError(name)
    return B, 4

def gram(B, scale):
    G = B @ B.T
    assert (G % (scale * scale) == 0).all()
    return G // (scale * scale)

