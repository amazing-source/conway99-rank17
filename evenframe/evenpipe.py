"""Even-sector class route at g' = 15 (k = 28): the even frame lattice L_beta (rank 15, det 2^8, 2-elementary, dual with
integral norms) lies with index 16 in a unimodular lattice U of rank 15, with 2U < L_beta.
  I = 2 L*/2U < U/2U : 4-dim, totally isotropic, doubly even (norms = 0 mod 4);  C = I^perp = L/2U.
  u0 = characteristic class of U.  W6 = (C cap u0^perp)/I with q(v) = |v|^2/2 mod 2 must be O+_6(2) = pairs of 8 points;
  cell {c,d} of the frame has class u0 + omega_cd + I, omega = the 21 pairs of 7 of the 8 points.
This module: lattice data, shells, classes mod 2, enumeration of I up to root transvections, skeletons, domains."""
import numpy as np, itertools, subprocess, os, sys, collections
from fractions import Fraction as Fr
import lat15

HERE = os.path.dirname(os.path.abspath(__file__))
FPK = os.path.join(HERE, '..', 'min8', 'fpk.exe')

def lll_gram(B):
    """exact LLL (delta = 3/4) on integer row basis B; returns reduced basis"""
    B = [list(map(int, r)) for r in B]
    n = len(B)
    def dot(a, b): return sum(x * y for x, y in zip(a, b))
    def gs():
        Bs = []; mu = [[Fr(0)] * n for _ in range(n)]
        for i in range(n):
            v = [Fr(x) for x in B[i]]
            for j in range(i):
                mu[i][j] = dot(B[i], Bs[j]) / dot(Bs[j], Bs[j])
                v = [a - mu[i][j] * b for a, b in zip(v, Bs[j])]
            Bs.append(v)
        return Bs, mu
    Bs, mu = gs(); k = 1
    while k < n:
        for j in range(k - 1, -1, -1):
            q = round(mu[k][j])
            if q:
                B[k] = [a - q * b for a, b in zip(B[k], B[j])]
                Bs, mu = gs()
        if dot(Bs[k], Bs[k]) >= (Fr(3, 4) - mu[k][k - 1] ** 2) * dot(Bs[k - 1], Bs[k - 1]):
            k += 1
        else:
            B[k], B[k - 1] = B[k - 1], B[k]
            Bs, mu = gs(); k = max(k - 1, 1)
    return np.array(B, dtype=np.int64)

def shell(G, target):
    """all x != 0 with x^T G x == target, both signs (fpk.exe gives them up to sign)"""
    n = len(G)
    inp = '%d %d\n' % (n, target) + '\n'.join(' '.join(str(int(x)) for x in row) for row in G) + '\n'
    out = subprocess.run([FPK], input=inp, capture_output=True, text=True).stdout
    X = np.array([list(map(int, l.split())) for l in out.split('\n') if l.strip()], dtype=np.int64).reshape(-1, n)
    assert ((X @ G) * X).sum(axis=1).tolist() == [target] * len(X)
    return np.vstack([X, -X])

PW = 1 << np.arange(15)
def cls(X): return ((X & 1) * PW).sum(axis=1)
def bits(c): return np.array([(c >> i) & 1 for i in range(15)], dtype=np.int64)

class Lat:
    def __init__(self, name):
        B, sc = lat15.build(name)
        B = lll_gram(B)
        self.name = name; self.B = B; self.sc = sc
        self.G = lat15.gram(B, sc)
        assert round(np.linalg.det(self.G.astype(float))) == 1
        G2 = self.G % 2
        self.G2 = G2
        # functional masks: f(c) = bits of (G c mod 2)
        allc = np.arange(1 << 15)
        bitsall = ((allc[:, None] >> np.arange(15)) & 1).astype(np.int64)
        self.FM = (((bitsall @ G2) % 2) * PW).sum(axis=1)          # functional of each class
        self.N4 = ((bitsall @ self.G) * bitsall).sum(axis=1) % 4      # norm mod 4 of each class
        # characteristic class: (x, u0) = (x, x) mod 2 for all x  <=> G u0 = diag(G) mod 2
        d = np.diag(self.G) % 2
        self.u0 = next(int(c) for c in allc if (((bitsall[c] @ G2) % 2) == d).all())
        self.S1 = shell(self.G, 1); self.S2 = shell(self.G, 2); self.S5 = shell(self.G, 5)
        self.rootcls = sorted(set(cls(self.S2).tolist()) - {0})
    def b(self, x, y): return bin(self.FM[x] & y).count('1') & 1

def enum_I(L, verbose=False):
    """4-dim doubly-even isotropic subspaces of U/2U up to the group generated by root transvections (lossless lexmin
    pruning on greedy-min bases; representatives may repeat within an Aut(U)-orbit)."""
    FM, N4 = L.FM, L.N4
    allc = np.arange(1 << 15)
    de = (N4 == 0) & (allc != 0)                                   # doubly-even nonzero classes
    RB = np.array(L.rootcls, dtype=np.int64); RF = FM[RB]
    par = lambda a, b: np.bitwise_count(a & b) & 1
    out = []
    def orbit_min(prefix):
        """union-find minima over all classes for transvections fixing every element of prefix"""
        p = allc.copy()
        gens = [k for k in range(len(RB)) if all((bin(int(RF[k]) & v).count('1') & 1) == 0 for v in prefix)]
        changed = True
        img = []
        for k in gens:
            t = np.where(par(allc, RF[k]) == 1, allc ^ RB[k], allc)
            img.append(t)
        # iterate min-propagation to a fixpoint (labels = min of orbit)
        lab = allc.copy()
        while changed:
            changed = False
            for t in img:
                m = np.minimum(lab, lab[t])
                m2 = m.copy(); np.minimum.at(m2, t, m)
                if (m2 != lab).any(): lab = m2; changed = True
        return lab
    def rec(prefix, span, ok):
        k = len(prefix)
        if k == 4:
            out.append(tuple(prefix)); return
        lab = orbit_min(prefix)
        cand = np.flatnonzero(ok & (lab == allc))
        last = prefix[-1] if prefix else 0
        sp = np.array(sorted(span), dtype=np.int64)
        for v in cand:
            v = int(v)
            if v <= last or v in span: continue
            coset = sp ^ v
            if coset.min() != v: continue                         # greedy-min basis: v = min of v + span
            if coset[1:].min() < last if len(coset) > 1 else False: pass
            ok2 = ok & (par(allc, int(FM[v])) == 0)
            rec(prefix + [v], span | set(coset.tolist()), ok2)
    rec([], {0}, de.copy())
    return out

if __name__ == '__main__':
    nm = sys.argv[1]
    L = Lat(nm)
    print(nm, 'norm1', len(L.S1), 'roots', len(L.S2), 'norm5', len(L.S5), 'root classes', len(L.rootcls), 'u0', L.u0, flush=True)
